/** End-to-end checks on the actual bundled repository runtime. No deployment. */
import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {chromium} from '../../tests/helpers/playwright.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const out=path.join(root,'preview-artifacts');
await fs.mkdir(path.join(out,'screenshots'),{recursive:true});
const protectedFiles=['index.html','app.js','seed-data.js','song-app.js','song-app.css','song-lib.js','song-seed.js'];
const hashes=async()=>Object.fromEntries(await Promise.all(protectedFiles.map(async f=>[f,createHash('sha256').update(await fs.readFile(path.join(root,f))).digest('hex')])));
const before=await hashes();
execFileSync(process.execPath,[path.join(root,'prototype/build.mjs')],{stdio:'inherit'});
assert.deepEqual(await hashes(),before,'Building must not edit the existing app');
const html=await fs.readFile(path.join(root,'prototype/dist/index.html'));
const server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html; charset=utf-8');res.end(html);});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const origin=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1440,height:1050},acceptDownloads:true,timezoneId:'America/Los_Angeles',reducedMotion:'reduce'});
const page=await context.newPage();
page.setDefaultTimeout(10000);
const report={checks:[{name:'Original application files unchanged by build',passed:true}],pageErrors:[],externalRequests:[],screenshots:[],sourceHashes:before};
page.on('pageerror',e=>report.pageErrors.push(String(e)));
page.on('request',r=>{if(!r.url().startsWith(origin)&&!r.url().startsWith('data:')&&!r.url().startsWith('blob:'))report.externalRequests.push(r.url());});
page.on('dialog',d=>d.accept());
const check=(name,actual,expected=true)=>{assert.deepEqual(actual,expected,name);report.checks.push({name,passed:true});console.log('PASS',name);};
const state=()=>page.evaluate(()=>Aurora.inspect().state);
const nav=async tab=>{await page.locator(`nav.tabs [data-tab="${tab}"]`).click();await page.waitForTimeout(80);};
const sub=async name=>{await page.locator(`[data-act="sub"][data-sub="${name}"]`).click();};
const shot=async name=>{await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:path.join(out,'screenshots',name+'.png')});report.screenshots.push(name+'.png');};
try {
 await page.goto(origin);
 await page.evaluate(()=>{window.localStorage.setItem('wds-me','PRODUCTION-SENTINEL');window.localStorage.setItem('unrelated-setting','KEEP');});
 check('Repository schedule, people and catalog preserved',await page.evaluate(()=>[Aurora.inspect().state.services.length,Aurora.inspect().state.members.length,SONG_SEED.songs.length]),[74,45,509]);
 check('Explicit frozen reference date',await page.evaluate(()=>new Aurora.Clock().getFullYear()+':'+new Aurora.Clock().getMonth()),'2026:6');
 check('No Firebase configured',await page.evaluate(()=>typeof window.FIREBASE_CONFIG),'undefined');
 check('No service worker registered',await page.evaluate(async()=> (await navigator.serviceWorker.getRegistrations()).length),0);
 check('Offline CSP enforced',await page.locator('meta[http-equiv="Content-Security-Policy"]').getAttribute('content').then(x=>x.includes("connect-src 'none'")));
 await shot('01-schedule-desktop');
 await page.locator('[data-aurora="service"]').last().click();
 check('Service-time selector',await page.evaluate(()=>Aurora.inspect().selection.service),'2026-07-04_evening');
 await page.locator('#a-department').selectOption('Usher Sisters');
 check('Department filter retains only requested category',await page.locator('.service-detail .cat-label').allTextContents(),['Usher Sisters']);
 await page.locator('#a-department').selectOption('All');
 await page.locator('[data-aurora="month"][data-step="-1"]').click();
 check('Empty past month recoverable',await page.locator('[data-aurora="reference-month"]').count(),1);
 await page.locator('#a-past').check();
 check('Past reference services available',await page.locator('.date-tile').count()>0);
 await page.locator('[data-aurora="month"][data-step="1"]').click();
 await page.locator('#a-search').fill('B. James');
 check('Search returns matching original services',await page.locator('.month-service').count()>0);
 await page.locator('#a-search').fill('<img src=x onerror=alert(1)>');
 check('Search safely escapes markup',await page.locator('#view img').count(),0);
 check('No-results state',await page.locator('#view').innerText().then(s=>s.includes('No services match')));
 await page.locator('#a-search').fill('');
 await nav('my');
 check('Original selected member preserved',await page.locator('#me-select').inputValue(),'B. Anthony L');
 await page.locator('[data-act="expand"]').first().click();
 check('Who else is serving expands',await page.locator('.duty-expand').count()>0);
 await page.locator('[data-act="notify-on"]').click();
 check('Notifications disclosed as unavailable offline',await page.locator('#aurora-toast').innerText().then(s=>s.includes('disabled')));
 const downloadPromise=page.waitForEvent('download');
 await page.locator('[data-act="subscribe-ics"]').click();
 const download=await downloadPromise;
 const ics=await fs.readFile(await download.path(),'utf8');
 check('Calendar snapshot retains Pacific timezone and both reminders',ics.includes('America/Los_Angeles')&&ics.includes('TRIGGER:-PT24H')&&ics.includes('TRIGGER:-PT2H'));
 await page.locator('[data-act="req-open"]').first().click();
 await page.locator('[data-chg="req-note"]').fill('Prototype change request');
 await page.locator('[data-act="req-submit"]').click();
 check('Original request submission',(await state()).requests.at(-1).note,'Prototype change request');
 await nav('manage');await sub('requests');
 const servicesBefore=(await state()).services;
 await page.locator('[data-act="req-approve"]').first().click();
 check('Original request approval',(await state()).requests.at(-1).status,'approved');
 check('Approval does not silently reassign a duty',(await state()).services,servicesBefore);
 await sub('services');
 await page.locator('[data-id="m:2026-07-04_morning"]').click();
 await page.locator('[data-chg="assign"][data-svc="2026-07-04_morning"][data-duty="Prayer of Thanks"]').selectOption('B. Davidson');
 check('Original assignment editor writes local preview',(await state()).services.find(s=>s.date==='2026-07-04'&&s.service==='Morning').assignments['Prayer of Thanks'],'B. Davidson');
 await page.reload();
 check('Edits survive reload',(await state()).services.find(s=>s.date==='2026-07-04'&&s.service==='Morning').assignments['Prayer of Thanks'],'B. Davidson');
 check('Production storage key untouched',await page.evaluate(()=>window.localStorage.getItem('wds-me')),'PRODUCTION-SENTINEL');
 check('Prayer + usher exception unchanged',await page.evaluate(()=>Aurora.conflictsFor({assignments:{'Closing Prayer':'A','Usher Door':'A'}}).length),0);
 check('Other duplicate assignments still flagged',await page.evaluate(()=>Aurora.conflictsFor({assignments:{'Presider':'A','Sermon':'A'}}).length),1);
 await nav('manage');
 for(const name of ['planning','people','features','data']){await sub(name);check(`Manage ${name} screen renders`,await page.locator('#view').innerText().then(s=>s.length>120));}
 await sub('features');
 check('Online sheet sync disabled in prototype',await page.locator('[data-chg="feature"][data-id="sheetSync"]').isDisabled());
 // The original switches visually hide their input. Click the visible label,
 // exactly as a member does, rather than forcing a hidden checkbox click.
 await page.locator('[data-chg="feature"][data-id="songPicker"]').locator('..').click();
 check('Song picker feature gate',await page.locator('#tab-presider').isHidden());
 await page.locator('[data-chg="feature"][data-id="songPicker"]').locator('..').click();
 await nav('my');
 await page.locator('[data-act="open-songs"]').first().click();
 await page.waitForSelector('#song-root [data-song-act="quick-add"]');
 check('My Duties deep-links to actual service setlist',await page.locator('#song-root').innerText().then(s=>s.includes('Sat, Jul 11')));
 check('Real catalog loaded in Presider',await page.locator('#song-root').innerText().then(s=>s.includes('509 songs')));
 await page.locator('[data-song-act="quick-add"]').nth(0).click();
 await page.locator('[data-song-act="quick-add"]').nth(1).click();
 check('Add songs with original duration total',await page.locator('.total-readout').innerText().then(s=>s.includes('4:24')&&s.includes('2 songs')));
 const titles=await page.locator('.set-row .s-title').allTextContents();
 await page.locator('[data-song-act="move-song"][aria-label="Move down"]').first().click();
 check('Setlist reorder',await page.locator('.set-row .s-title').allTextContents(),[titles[1],titles[0]]);
 await page.locator('[data-song-act="remove-song"]').first().click();
 check('Remove song',await page.locator('.set-row').count(),1);
 await page.locator('[data-song-act="quick-add"]').nth(1).click();
 await page.locator('[data-song-act="confirm-songs"]').first().click();
 check('Setlist confirmation',await page.locator('.confirm-box').innerText().then(s=>s.includes('Songs confirmed')));
 await shot('02-presider-library-desktop');
 for(const tab of ['home','services','insights','library']){await page.locator(`[data-song-act="tab"][data-tab="${tab}"]`).click();check(`Presider ${tab} renders`,await page.locator('#song-root').innerText().then(s=>s.length>150));}
 await page.reload();await nav('my');await page.locator('[data-act="open-songs"]').first().click();
 await page.waitForSelector('#song-root .set-row');
 check('Setlist persists after reload',await page.locator('.set-row').count(),2);
 for(const screen of ['schedule','my','songs','manage']){
  await nav(screen);
  for(const width of [320,390,768,1024,1440]){
   await page.setViewportSize({width,height:900});
   check(`No horizontal page overflow: ${screen} at ${width}`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
   if(width===390)await shot(`mobile-${screen}`);
  }
 }
 await nav('schedule');
 await page.locator('[data-aurora="theme"]').click();
 check('Dark theme',await page.locator('body').evaluate(el=>el.classList.contains('dark')));
 await shot('03-schedule-dark');
 await page.locator('[data-aurora="motion"]').click();
 check('Animation pause control',await page.locator('body').evaluate(el=>el.classList.contains('still')));
 await page.reload();
 check('Appearance preferences persist',await page.locator('body').evaluate(el=>el.classList.contains('dark')&&el.classList.contains('still')));
 await nav('my');await page.locator('#me-select').selectOption('S. Mercie');
 check('Non-presider role gate',await page.locator('#tab-presider').isHidden());
 await page.locator('[data-aurora="reset"]').click();
 await page.waitForLoadState();await page.waitForSelector('#a-search');
 check('Reset restores only preview assignment edits',(await state()).services.find(s=>s.date==='2026-07-04'&&s.service==='Morning').assignments['Prayer of Thanks'],'B. Brent');
 check('Reset preserves production and unrelated storage',await page.evaluate(()=>[window.localStorage.getItem('wds-me'),window.localStorage.getItem('unrelated-setting')]),['PRODUCTION-SENTINEL','KEEP']);
 check('Zero external network requests',report.externalRequests,[]);
 check('Zero runtime errors',report.pageErrors,[]);
 report.passed=true;
} catch(e){
 report.passed=false;report.failure=String(e.stack||e);
 await shot('failure').catch(()=>{});throw e;
} finally {
 report.count=report.checks.length;
 await fs.writeFile(path.join(out,'test-report.json'),JSON.stringify(report,null,2));
 await fs.writeFile(path.join(out,'LV_Zion_Aurora_Prototype.html'),html);
 console.log(JSON.stringify({passed:report.passed,checks:report.count,failure:report.failure},null,2));
 await browser.close();await new Promise(resolve=>server.close(resolve));
}
